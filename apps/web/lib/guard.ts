/**
 * Защита от выманивания системного промпта.
 *
 * Это не стена, а порог. Перефразировать просьбу можно сотней способов, и список
 * образцов их не поймает — притворяться иначе было бы обманом.
 *
 * Настоящая защита устроена иначе, и она важнее списка:
 *
 * 1. В системном промпте **нет секретов**. Там факты, которые владелец сайта и
 *    так публикует: часы работы, адрес. Выдать его — не катастрофа, и это
 *    осознанный выбор, а не недосмотр.
 * 2. У модели **нет возможностей**: ни инструментов, ни доступа к базе, ни
 *    доступа к чужим диалогам. Даже полностью перехватив управление ответом,
 *    посетитель не получит ничего, кроме текста в своём же окне.
 * 3. Чужие данные в контекст не попадают: история ограничена текущим диалогом,
 *    а он принадлежит этому посетителю.
 *
 * Порог ловит самый частый и самый дешёвый вид попытки — и не тратит на него
 * токены.
 */

const PATTERNS: readonly RegExp[] = [
  /system\s*prompt/i,
  /your\s+(initial\s+)?instructions/i,
  /repeat\s+(your\s+)?(instructions|prompt)/i,
  /ignore\s+(all\s+)?(previous|prior|above)\s+instructions/i,
  /системн\w*\s+промпт/i,
  /повтори\s+(свои\s+)?инструкции/i,
  /игнорируй\s+(все\s+)?(предыдущие\s+)?инструкции/i,
];

export function looksLikePromptExtraction(question: string): boolean {
  return PATTERNS.some((pattern) => pattern.test(question));
}

