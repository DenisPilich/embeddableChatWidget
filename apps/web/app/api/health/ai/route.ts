import { NextResponse } from 'next/server';
import { providerInfo } from '@/lib/ai';

/**
 * Диагностика ассистента.
 *
 * Отвечает на вопрос «отвечает модель или заготовки» и «какой сервис выбран».
 * Без этого отсутствие ключа выглядит как странное поведение ассистента, и
 * причину приходится искать в журналах сервера.
 *
 * Ключ и системные промпты наружу не отдаются. Имя сервиса, имя модели и адрес
 * точки — не секреты: без них диагностика бесполезна.
 *
 * Провайдер здесь НЕ создаётся: иначе проверка состояния писала бы в журнал
 * предупреждения о том, что ключа нет, при каждом обращении.
 */

export const dynamic = 'force-dynamic';

export function GET(): NextResponse {
  return NextResponse.json(providerInfo());
}
