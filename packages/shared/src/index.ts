/**
 * Общий контракт между виджетом, бэкендом и дашбордом.
 *
 * Здесь живут только типы и константы — никакого кода, зависящего от браузера
 * или от Node. Это позволяет использовать пакет и на клиенте, и на сервере,
 * и он специально не имеет доступа к DOM: ошибка «использовал document в общем
 * пакете» должна ловиться компилятором, а не в рантайме на проде.
 */

/**
 * Версия публичного контракта.
 * Виджет, уже встроенный на чужие сайты, живёт там годами и не обновляется
 * вместе с бэкендом, поэтому несовместимые изменения контракта оформляются
 * новой версией, а не правкой старой.
 */
export const CONTRACT_VERSION = 1;

/** Публичный идентификатор сайта. Не секрет: он виден в HTML любого клиента. */
export type SiteId = string;

/** Кто автор сообщения в переписке. */
export type AuthorKind = 'visitor' | 'ai' | 'agent';

/** Сообщение в диалоге. */
export interface ChatMessage {
  id: string;
  /**
   * Монотонный номер внутри диалога.
   * Клиент запрашивает «всё, что после seq=N» — это защищает от дубликатов
   * и пропусков при периодическом опросе, в отличие от запроса «последние 50».
   */
  seq: number;
  conversationId: string;
  authorKind: AuthorKind;
  body: string;
  /**
   * Идентификатор, который присвоил отправитель. Есть только у сообщений
   * посетителя.
   *
   * Нужен виджету, чтобы узнать собственное сообщение, вернувшееся в общем
   * списке: он уже показал его посетителю и не должен показывать второй раз.
   */
  clientId?: string;
  /** Момент создания в формате ISO 8601. */
  createdAt: string;
}

/** Внешний вид виджета, заданный владельцем сайта. */
export interface WidgetAppearance {
  /** Основной цвет, например `#4338ca`. */
  color: string | null;
  /** Заголовок окна. */
  title: string | null;
  /** Первое сообщение в пустой переписке. */
  greeting: string | null;
}

/**
 * Что делает пункт меню.
 *
 * Набор намеренно короткий. Всё, чего в нём нет, владелец выражает текстом
 * ответа или порядком пунктов: шестистрочный список действий понятен, а
 * «конструктор сценариев» — нет, и им никто не пользуется.
 */
export type MenuAction = 'answer' | 'operator' | 'submenu' | 'ai';

/**
 * Пункт меню, который видит посетитель.
 *
 * Приходит деревом: подменю — это те же пункты внутри `children`. Дерево
 * собирается на сервере один раз, чтобы виджет не разбирался в связях.
 */
export interface MenuItem {
  id: string;
  /** Текст на кнопке. */
  label: string;
  action: MenuAction;
  /** Текст ответа. Есть только у `answer`. */
  answer: string | null;
  children: MenuItem[];
}

/** Ответ на первый запрос виджета. */
export interface InitResponse {
  /** Подписанный токен. Виджет приносит его в заголовке Authorization. */
  token: string;
  conversationId: string;
  /** Номер последнего сообщения в диалоге на момент ответа. */
  lastSeq: number;
  /**
   * Ждёт ли диалог живого оператора.
   *
   * Виджет показывает это посетителю: иначе он писал бы в пустоту, не понимая,
   * почему ассистент перестал отвечать.
   */
  waitingForHuman: boolean;
  /**
   * Внешний вид, заданный владельцем сайта.
   *
   * Приходит вместе с сессией, а не отдельным запросом: вид нужен сразу, и
   * второй запрос ради цвета означал бы мигание окна при открытии.
   */
  appearance: WidgetAppearance;
  /**
   * Пункты меню верхнего уровня. Пусто — меню нет, и виджет работает как
   * обычный чат с полем ввода.
   */
  menu: MenuItem[];
  /**
   * Отвечает ли ассистент на свободные вопросы.
   *
   * Выключено у сайта, где владелец хочет только меню: тогда поле ввода не
   * появляется, а пункт «свой вопрос» скрывается.
   */
  aiEnabled: boolean;
  /**
   * Сколько секунд ждать оператора, прежде чем предложить оставить телефон.
   * Настраивается владельцем сайта.
   */
  handoverTimeout: number;
  /**
   * Когда попросили оператора (ISO 8601) или `null`.
   *
   * По этому времени виджет считает, сколько ещё ждать: посетитель мог закрыть
   * вкладку в середине ожидания, и отсчёт обязан продолжиться с того же места.
   */
  humanRequestedAt: string | null;
  /** Оставленный телефон или `null`, если его ещё не оставляли. */
  phone: string | null;
}

/** Ответ на выбор пункта меню. */
export interface MenuClickResponse {
  /** Сообщения, которые появились в переписке от этого выбора. */
  messages: ChatMessage[];
  waitingForHuman: boolean;
  humanRequestedAt: string | null;
}

/** Ответ на оставленный телефон. */
export interface PhoneResponse {
  /** Сообщение-подтверждение, появившееся в переписке. */
  message: ChatMessage;
  phone: string;
}

/**
 * Состояние разговора.
 *
 * Отдельный объект, потому что смотреть на него надо целиком: «ждём человека»,
 * «ведёт человек», «отвечает ассистент», «разговор закрыт» — вещи
 * взаимоисключающие, и разбирать их по отдельным полям значит рано или поздно
 * перепутать.
 */
export interface ConversationState {
  waitingForHuman: boolean;
  humanRequestedAt: string | null;
  /** Отвечает ли ассистент: включается только пунктом «свой вопрос». */
  aiMode: boolean;
  /** Отвечал ли живой оператор. */
  humanJoined: boolean;
  /** Закрыт ли разговор: виджет возвращается к меню. */
  closed: boolean;
}

/** Ответ на выборку новых сообщений. */
export interface MessagesResponse {
  messages: ChatMessage[];
  /** Номер последнего отданного сообщения: его клиент запомнит как курсор. */
  lastSeq: number;
  /**
   * Состояние разговора на момент ответа.
   *
   * Виджет узнаёт отсюда, что оператор закрыл разговор, и возвращается к меню —
   * отдельный запрос ради этого не нужен.
   */
  state: ConversationState;
}

/** Ответ на отправку сообщения. */
export interface SendMessageResponse {
  message: ChatMessage;
  /** Истина, если сообщение уже было записано раньше: повторная отправка. */
  duplicate: boolean;
}

/**
 * Коды ошибок API.
 *
 * Виджет по ним решает, что делать: показать посетителю сообщение, повторить
 * запрос или сдаться. Поэтому коды машинные и перечислены здесь, а не
 * «придумываются» на каждом эндпоинте.
 */
export type ApiErrorCode =
  | 'invalid_request'
  | 'unknown_site'
  | 'origin_not_allowed'
  | 'unauthorized'
  | 'empty_message'
  | 'conversation_not_found'
  | 'rate_limited'
  | 'server_error';
