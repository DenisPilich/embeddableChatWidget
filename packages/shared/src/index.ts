/**
 * Общий контракт между виджетом, бэкендом и дашбордом.
 *
 * Здесь живут только типы и константы — никакого кода, зависящего от браузера
 * или от Node. Это позволяет использовать пакет и на клиенте, и на сервере,
 * и он специально не имеет доступа к DOM: ошибка «использовал document в общем
 * пакете» должна ловиться компилятором, а не в рантайме на проде.
 */

/**
 * Версия публичного контракта.
 * Виджет, уже встроенный на чужие сайты, живёт там годами и не обновляется
 * вместе с бэкендом, поэтому несовместимые изменения контракта оформляются
 * новой версией, а не правкой старой.
 */
export const CONTRACT_VERSION = 1;

/** Публичный идентификатор сайта. Не секрет: он виден в HTML любого клиента. */
export type SiteId = string;

/** Кто автор сообщения в переписке. */
export type AuthorKind = 'visitor' | 'ai' | 'agent';

/** Сообщение в диалоге. */
export interface ChatMessage {
  id: string;
  /**
   * Монотонный номер внутри диалога.
   * Клиент запрашивает «всё, что после seq=N» — это защищает от дубликатов
   * и пропусков при периодическом опросе, в отличие от запроса «последние 50».
   */
  seq: number;
  conversationId: string;
  authorKind: AuthorKind;
  body: string;
  /** Момент создания в формате ISO 8601. */
  createdAt: string;
}
