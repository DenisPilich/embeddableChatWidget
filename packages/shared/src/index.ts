/**
 * Общий контракт между виджетом, бэкендом и дашбордом.
 *
 * Здесь живут только типы и константы — никакого кода, зависящего от браузера
 * или от Node. Это позволяет использовать пакет и на клиенте, и на сервере,
 * и он специально не имеет доступа к DOM: ошибка «использовал document в общем
 * пакете» должна ловиться компилятором, а не в рантайме на проде.
 */

/**
 * Версия публичного контракта.
 * Виджет, уже встроенный на чужие сайты, живёт там годами и не обновляется
 * вместе с бэкендом, поэтому несовместимые изменения контракта оформляются
 * новой версией, а не правкой старой.
 */
export const CONTRACT_VERSION = 1;

/** Публичный идентификатор сайта. Не секрет: он виден в HTML любого клиента. */
export type SiteId = string;

/** Кто автор сообщения в переписке. */
export type AuthorKind = 'visitor' | 'ai' | 'agent';

/** Сообщение в диалоге. */
export interface ChatMessage {
  id: string;
  /**
   * Монотонный номер внутри диалога.
   * Клиент запрашивает «всё, что после seq=N» — это защищает от дубликатов
   * и пропусков при периодическом опросе, в отличие от запроса «последние 50».
   */
  seq: number;
  conversationId: string;
  authorKind: AuthorKind;
  body: string;
  /**
   * Идентификатор, который присвоил отправитель. Есть только у сообщений
   * посетителя.
   *
   * Нужен виджету, чтобы узнать собственное сообщение, вернувшееся в общем
   * списке: он уже показал его посетителю и не должен показывать второй раз.
   */
  clientId?: string;
  /** Момент создания в формате ISO 8601. */
  createdAt: string;
}

/** Ответ на первый запрос виджета. */
export interface InitResponse {
  /** Подписанный токен. Виджет приносит его в заголовке Authorization. */
  token: string;
  conversationId: string;
  /** Номер последнего сообщения в диалоге на момент ответа. */
  lastSeq: number;
}

/** Ответ на выборку новых сообщений. */
export interface MessagesResponse {
  messages: ChatMessage[];
  /** Номер последнего отданного сообщения: его клиент запомнит как курсор. */
  lastSeq: number;
}

/** Ответ на отправку сообщения. */
export interface SendMessageResponse {
  message: ChatMessage;
  /** Истина, если сообщение уже было записано раньше: повторная отправка. */
  duplicate: boolean;
}

/**
 * Коды ошибок API.
 *
 * Виджет по ним решает, что делать: показать посетителю сообщение, повторить
 * запрос или сдаться. Поэтому коды машинные и перечислены здесь, а не
 * «придумываются» на каждом эндпоинте.
 */
export type ApiErrorCode =
  | 'invalid_request'
  | 'unknown_site'
  | 'origin_not_allowed'
  | 'unauthorized'
  | 'empty_message'
  | 'conversation_not_found'
  | 'server_error';
