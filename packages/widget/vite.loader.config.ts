import { defineConfig } from 'vite';

/**
 * Сборка загрузчика — отдельная конфигурация, а не вторая точка входа в
 * основную.
 *
 * Причина техническая: формат IIFE не поддерживает несколько точек входа.
 * Несколько входов требуют разделения кода на общие куски, а в IIFE такого
 * механизма нет — сборщик просто отказывается собирать. Две конфигурации
 * оказались честнее и понятнее, чем попытка обойти это ограничение.
 *
 * Загрузчик собирается только в IIFE: его подключают тегом `<script>`. Тем,
 * кто ставит пакет из npm, загрузчик не нужен — они импортируют виджет напрямую.
 */
export default defineConfig({
  build: {
    lib: {
      entry: 'src/loader.ts',
      name: 'ECWLoader',
      formats: ['iife'],
      fileName: () => 'ecw-loader.iife.js',
    },
    target: 'es2020',
    sourcemap: true,
    // Критично: НЕ очищать папку сборки. Иначе вторая сборка стирает результат
    // первой, и в dist остаётся только загрузчик без основного файла.
    emptyOutDir: false,
  },
});
