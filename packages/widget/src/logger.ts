/**
 * Отладочные сообщения виджета.
 *
 * Это единственное место в пакете, которому разрешено писать в консоль, и только
 * тогда, когда отладку включили явно: `window.ECW_DEBUG = true`. На чужой
 * странице любое наше сообщение — мусор в консоли клиента, поэтому правило
 * `no-console` запрещает это везде, кроме этого модуля.
 *
 * Предупреждения и ошибки (warn/error) пишутся напрямую в местах возникновения —
 * они сообщают о нашей проблеме, и их полезно видеть даже без отладки.
 */
export function log(...args: unknown[]): void {
  if (typeof window === 'undefined' || !window.ECW_DEBUG) return;
  // eslint-disable-next-line no-console -- см. пояснение к модулю
  console.info('[ecw]', ...args);
}
