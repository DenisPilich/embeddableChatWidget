import type { ChatMessage } from '@ecw/shared';

/**
 * Транспорт: как сообщения попадают на сервер и возвращаются обратно.
 *
 * Виджет знает только эти действия и не знает, что за ними: опрос, SSE,
 * WebSocket или выдуманный сервер. Это не украшательство, а необходимость.
 * Способ доставки приходится менять — сначала появился настоящий опрос, затем
 * поток, и, возможно, будет что-то ещё. Без такой границы каждая замена означала
 * бы правку виджета, то есть риск сломать то, что уже работает на чужих сайтах.
 *
 * Смысл разделения в том, что интерфейс описывают ПО ТРЕБНОСТЯМ ВИДЖЕТА, а не
 * по возможностям конкретного сервиса. Поэтому здесь нет ни токенов, ни адресов,
 * ни номеров сообщений: всё это внутренние дела реализации.
 */

/** Сообщение, которое посетитель отправляет. */
export interface OutgoingMessage {
  /**
   * Идентификатор, присвоенный виджетом. Нужен по двум причинам: на нём
   * держится защита от повторной отправки, и по нему виджет потом узнаёт своё
   * сообщение, если сервер вернёт его в общем списке.
   */
  clientId: string;
  body: string;
}

export type MessagesHandler = (messages: readonly ChatMessage[]) => void;

/** Кусок ответа, пришедший раньше, чем ответ готов целиком. */
export type DeltaHandler = (text: string) => void;

export interface Transport {
  /**
   * Открывает сессию. Вызывается один раз при запуске виджета.
   *
   * Неудача здесь означает, что разговаривать нельзя вовсе: например, домен
   * сайта не разрешён на сервере. Ошибку разбирает тот, кто транспорт создал.
   */
  connect(): Promise<void>;

  /**
   * Отдаёт сообщение посетителя.
   *
   * Успешное завершение означает «сервер принял и записал», а не «ассистент
   * ответил». Ответ придёт позже и отдельно — через подписки. Он может не
   * прийти вовсе, и это не будет ошибкой отправки.
   *
   * Правило реализации: сообщение, ушедшее через `send`, в подписку НЕ
   * возвращается. Виджет уже показал его посетителю, и повторная доставка
   * выглядела бы как дубль.
   */
  send(message: OutgoingMessage): Promise<void>;

  /** Подписка на сообщения, появившиеся в диалоге. */
  onMessages(handler: MessagesHandler): void;

  /**
   * Подписка на текст ответа по мере появления.
   *
   * Реализация, которая не умеет отдавать промежуточный текст, просто никогда не
   * вызывает обработчик: тогда виджет покажет ответ целиком, когда тот придёт.
   * Поэтому метод обязателен для реализации, а поведение — нет: виджет не
   * должен знать, умеет ли конкретный способ доставки отдавать куски.
   */
  onDelta(handler: DeltaHandler): void;

  /** Прекращает работу: останавливает опрос, закрывает соединение. */
  close(): void;
}
