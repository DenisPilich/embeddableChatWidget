import type { ChatMessage, ConversationState, MenuItem, WidgetAppearance } from '@ecw/shared';

/**
 * Транспорт: как сообщения попадают на сервер и возвращаются обратно.
 *
 * Виджет знает только эти действия и не знает, что за ними: опрос, SSE,
 * WebSocket или выдуманный сервер. Это не украшательство, а необходимость.
 * Способ доставки приходится менять — сначала появился настоящий опрос, затем
 * поток, и, возможно, будет что-то ещё. Без такой границы каждая замена означала
 * бы правку виджета, то есть риск сломать то, что уже работает на чужих сайтах.
 *
 * Смысл разделения в том, что интерфейс описывают ПО ТРЕБНОСТЯМ ВИДЖЕТА, а не
 * по возможностям конкретного сервиса. Поэтому здесь нет ни токенов, ни адресов,
 * ни номеров сообщений: всё это внутренние дела реализации.
 */

/** Сообщение, которое посетитель отправляет. */
export interface OutgoingMessage {
  /**
   * Идентификатор, присвоенный виджетом. Нужен по двум причинам: на нём
   * держится защита от повторной отправки, и по нему виджет потом узнаёт своё
   * сообщение, если сервер вернёт его в общем списке.
   */
  clientId: string;
  body: string;
}

export type MessagesHandler = (messages: readonly ChatMessage[]) => void;

/** Кусок ответа, пришедший раньше, чем ответ готов целиком. */
export type DeltaHandler = (text: string) => void;

/** Состояние разговора, пришедшее с сервером. */
export type StateHandler = (state: ConversationState) => void;

/** Что вернул выбор пункта меню. */
export interface MenuChoice {
  /** Сообщения, появившиеся в переписке от этого выбора. */
  messages: readonly ChatMessage[];
  waitingForHuman: boolean;
  /** Момент просьбы об операторе, мс эпохи, или null. */
  waitingSince: number | null;
}

/** Что вернуло оставление телефона. */
export interface PhoneLeft {
  message: ChatMessage;
  phone: string;
}

export interface Transport {
  /**
   * Открывает сессию. Вызывается один раз при запуске виджета.
   *
   * Неудача здесь означает, что разговаривать нельзя вовсе: например, домен
   * сайта не разрешён на сервере. Ошибку разбирает тот, кто транспорт создал.
   */
  connect(): Promise<void>;

  /**
   * Отдаёт сообщение посетителя.
   *
   * Успешное завершение означает «сервер принял и записал», а не «ассистент
   * ответил». Ответ придёт позже и отдельно — через подписки. Он может не
   * прийти вовсе, и это не будет ошибкой отправки.
   *
   * Правило реализации: сообщение, ушедшее через `send`, в подписку НЕ
   * возвращается. Виджет уже показал его посетителю, и повторная доставка
   * выглядела бы как дубль.
   */
  send(message: OutgoingMessage): Promise<void>;

  /** Подписка на сообщения, появившиеся в диалоге. */
  onMessages(handler: MessagesHandler): void;

  /**
   * Подписка на изменение состояния разговора.
   *
   * Приходит с каждым опросом, но обработчик вызывается только когда состояние
   * изменилось. По нему виджет узнаёт, что оператор закрыл разговор, и
   * возвращается к меню.
   */
  onState(handler: StateHandler): void;

  /**
   * Подписка на текст ответа по мере появления.
   *
   * Реализация, которая не умеет отдавать промежуточный текст, просто никогда не
   * вызывает обработчик: тогда виджет покажет ответ целиком, когда тот придёт.
   * Поэтому метод обязателен для реализации, а поведение — нет: виджет не
   * должен знать, умеет ли конкретный способ доставки отдавать куски.
   */
  onDelta(handler: DeltaHandler): void;

  /**
   * Подписка на «ответа не будет».
   *
   * Так бывает, когда диалог ждёт живого оператора: ассистент молчит, чтобы не
   * перебивать человека. Без такого сигнала виджет показывал бы «печатает…»
   * бесконечно, и посетитель решил бы, что всё зависло.
   */
  onIdle(handler: () => void): void;

  /**
   * Просит живого оператора.
   *
   * Отдельное действие, а не сообщение: посетитель не пишет текст, он нажимает
   * кнопку, и в переписке это должно выглядеть как просьба, а не как реплика.
   */
  requestHuman(): Promise<void>;

  /** Ждёт ли диалог оператора. Известно после `connect`. */
  readonly waitingForHuman: boolean;

  /**
   * Вид, заданный владельцем сайта, или `null`, если вид по умолчанию.
   * Известен после `connect`.
   */
  readonly appearance: WidgetAppearance | null;

  /**
   * Пункты меню, настроенные владельцем сайта. Пусто — меню нет, и виджет
   * работает как обычный чат с полем ввода.
   */
  readonly menu: readonly MenuItem[];

  /** Отвечает ли ассистент на свободные вопросы. Известно после `connect`. */
  readonly aiEnabled: boolean;

  /** Сколько секунд ждать оператора, прежде чем предложить телефон. */
  readonly handoverTimeout: number;

  /** Когда попросили оператора (мс эпохи) или `null`. Нужно для отсчёта. */
  readonly waitingSince: number | null;

  /** Телефон, уже оставленный посетителем, или `null`. */
  readonly phone: string | null;

  /**
   * Выбор пункта меню.
   *
   * Отдельное действие, а не сообщение: нажатие может значить «покажи ответ»,
   * «позови человека» или «открой подменю». Возвращает появившиеся сообщения,
   * чтобы виджет показал их сразу, не дожидаясь опроса.
   */
  chooseMenuItem(optionId: string): Promise<MenuChoice>;

  /** Оставляет телефон вместо ожидания оператора. */
  leavePhone(phone: string): Promise<PhoneLeft>;

  /** Прекращает работу: останавливает опрос, закрывает соединение. */
  close(): void;
}
